"""Generate a self-contained SQL file (no psql needed) that loads the T1
incidents of both cities into incident_report. Run it in pgAdmin's Query Tool.

Usage: python make_import_sql.py cityA cityB
Output: data/processed/import_incidents_inline.sql

Idempotent: first removes rows this script inserted earlier (description starts with
'police.uk '), so re-running never duplicates. Reports are spread round-robin over
users 1..5; timestamp = <month>-15 12:00.
"""
import sys
import pandas as pd
import config as C

CHUNK = 2000


def main(cities):
    inc = pd.concat([pd.read_csv(C.DATA_PROC / f"{c}_incidents.csv") for c in cities], ignore_index=True)
    inc = inc[inc.period == "T1"].reset_index(drop=True)
    out = C.DATA_PROC / "import_incidents_inline.sql"
    with open(out, "w", encoding="utf-8") as f:
        f.write("-- generated by make_import_sql.py; T1 incidents of " + ", ".join(cities) + "\n")
        f.write("BEGIN;\nDELETE FROM incident_report WHERE description LIKE 'police.uk %';\n")
        f.write("CREATE TEMP TABLE stg_incident (category text, month text, lat double precision, "
                "lng double precision, n int) ON COMMIT DROP;\n")
        for i in range(0, len(inc), CHUNK):
            rows = ",\n".join(f"('{r.category}','{r.month}',{r.lat},{r.lng},{i + k + 1})"
                              for k, r in enumerate(inc.iloc[i:i + CHUNK].itertuples()))
            f.write(f"INSERT INTO stg_incident VALUES\n{rows};\n")
        f.write("""
-- every category must match a seeded category (matched = true on every row)
SELECT s.category, count(*) AS rows, bool_or(c.id IS NOT NULL) AS matched
FROM stg_incident s LEFT JOIN incident_category c ON lower(c.name) = lower(s.category) GROUP BY s.category;

INSERT INTO incident_report
  (description, latitude, longitude, "timestamp", is_anonymous, upvotes, downvotes, user_id, category_id, status)
SELECT 'police.uk ' || s.category || ' ' || s.month, s.lat, s.lng,
       (s.month || '-15 12:00:00')::timestamp, true, 0, 0, 1 + (s.n % 5), c.id, 'ACTIVE'
FROM stg_incident s JOIN incident_category c ON lower(c.name) = lower(s.category);

SELECT c.name, count(*) FROM incident_report r JOIN incident_category c ON c.id = r.category_id
WHERE r.description LIKE 'police.uk %' GROUP BY c.name ORDER BY 2 DESC;
COMMIT;
""")
    print(f"{len(inc)} T1 incidents -> {out}")


if __name__ == "__main__":
    main(sys.argv[1:])
